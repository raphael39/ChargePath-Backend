def get_vehicle(vehicle_id: str = "generic_ev") -> VehicleSpecs:
    """Holt die Fahrzeugdaten anhand der ID.

    Faellt auf ``generic_ev`` zurueck, wenn die ID unbekannt ist. Legacy-IDs
    wie ``tesla_model_3_lr`` werden via Aliase auf die aktuellste Variante
    gemappt.
    """
    return VEHICLE_DB.get(vehicle_id, VEHICLE_DB["generic_ev"])


def list_vehicles() -> List[Dict[str, str]]:
    """Liefert eine kompakte Liste aller verfuegbaren Vehicles fuer die App-UI.

    Returns:
        List of dicts mit Keys: ``id``, ``name``, ``model_year_range``,
        ``battery_capacity_kwh``, ``max_charge_power_kw``, ``architecture_voltage``.

    Legacy-Aliase werden ausgefiltert (zeigen nur die kanonischen IDs).
    """
    legacy_aliases = {"tesla_model_3_lr", "tesla_model_y_lr", "vw_id4_pro"}
    return [
        {
            "id": v.id,
            "name": v.name,
            "model_year_range": v.model_year_range,
            "battery_capacity_kwh": v.battery_capacity_kwh,
            "max_charge_power_kw": v.max_charge_power_kw,
            "architecture_voltage": v.architecture_voltage,
        }
        for vid, v in VEHICLE_DB.items()
        if vid not in legacy_aliases
    ]
